<?php

namespace App\Services\Laporan\Word\Builders;

use PhpOffice\PhpWord\Element\Section;

class TableBuilder
{

    private const HEADER_STYLE = [
        'bold' => true,
        'size' => 10,
    ];

    private const BODY_STYLE = [
        'size' => 10,
    ];

    private const HEADER_CELL = [
        'bgColor' => 'D9EAD3',
        'valign' => 'center',
    ];

    private const BODY_CELL = [
        'valign' => 'center',
    ];

    private const HEADER_PARAGRAPH = [
        'alignment' => 'center',
        'spaceAfter' => 0,
    ];

    private const BODY_CENTER = [
        'alignment' => 'center',
        'spaceAfter' => 0,
    ];

    private const BODY_LEFT = [
        'alignment' => 'left',
        'spaceAfter' => 0,
        'keepNext' => true,
    ];

    private function rowColor(
        int $index
    ): string {

        return $index % 2 === 0
            ? 'FFFFFF'
            : 'F8F9FA';

    }

    private function paragraphStyle(
        int $column
    ): array {

        return match ($column) {

            /*
            |--------------------------------------------------------------------------
            | Center
            |--------------------------------------------------------------------------
            */

            0,
            1,
            4,
            6,
            7,
            8,
            9,
            10
            => self::BODY_CENTER,

            /*
            |--------------------------------------------------------------------------
            | Left
            |--------------------------------------------------------------------------
            */

            default
            => self::BODY_LEFT,

        };

    }

    private function columnWidth(
        int $column
    ): int {

        return match ($column) {

            /*
            |--------------------------------------------------------------------------
            | No
            |--------------------------------------------------------------------------
            */

            0 => 500,

            /*
            |--------------------------------------------------------------------------
            | Kode Tiket
            |--------------------------------------------------------------------------
            */

            1 => 1700,

            /*
            |--------------------------------------------------------------------------
            | Pemohon
            |--------------------------------------------------------------------------
            */

            2 => 2200,

            /*
            |--------------------------------------------------------------------------
            | Lokasi
            |--------------------------------------------------------------------------
            */

            3 => 3500,

            /*
            |--------------------------------------------------------------------------
            | Kepemilikan
            |--------------------------------------------------------------------------
            */

            4 => 1700,

            /*
            |--------------------------------------------------------------------------
            | Teknisi
            |--------------------------------------------------------------------------
            */

            5 => 2000,

            /*
            |--------------------------------------------------------------------------
            | Status
            |--------------------------------------------------------------------------
            */

            6 => 1200,

            /*
            |--------------------------------------------------------------------------
            | Kategori
            |--------------------------------------------------------------------------
            */

            7 => 1200,

            /*
            |--------------------------------------------------------------------------
            | Mulai
            |--------------------------------------------------------------------------
            */

            8 => 1700,

            /*
            |--------------------------------------------------------------------------
            | Selesai
            |--------------------------------------------------------------------------
            */

            9 => 1700,

            /*
            |--------------------------------------------------------------------------
            | Durasi
            |--------------------------------------------------------------------------
            */

            10 => 1800,

            default => 1500,

        };

    }

    /**
     * Build Table
     */
    public function build(
        Section $section,
        array $headers,
        array $rows
    ): void {

        $table = $section->addTable('MainTable');

        /*
        |--------------------------------------------------------------------------
        | Header
        |--------------------------------------------------------------------------
        */

        $table->addRow(
            500,
            [
                'tblHeader' => true,
            ]
        );

        foreach ($headers as $column => $header) {

            $table
                ->addCell(
                    $this->columnWidth($column),
                    self::HEADER_CELL
                )
                ->addText(
                    $header,
                    self::HEADER_STYLE,
                    self::HEADER_PARAGRAPH
                );

        }

        /*
        |--------------------------------------------------------------------------
        | Body
        |--------------------------------------------------------------------------
        */

        foreach ($rows as $rowIndex => $row) {

            $table->addRow(380);

            foreach ($row as $column => $value) {

                $table
                    ->addCell(
                        $this->columnWidth($column),
                        array_merge(
                            self::BODY_CELL,
                            [
                                'bgColor' => $this->rowColor($rowIndex),
                            ]
                        )
                    )
                    ->addText(
                        (string) $value,
                        self::BODY_STYLE,
                        $this->paragraphStyle($column)
                    );

            }

        }

    }
}

